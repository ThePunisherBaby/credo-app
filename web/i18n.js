export function detectLocale() {
  try {
    const saved = localStorage.getItem('credo-locale');
    if (saved && CREDO_I18N[saved]) return saved;
  } catch {}
  const nav = (navigator.language || 'es').slice(0, 2).toLowerCase();
  return CREDO_I18N[nav] ? nav : 'es';
}

export function getDict(lang) {
  return CREDO_I18N[lang] || CREDO_I18N.es;
}
